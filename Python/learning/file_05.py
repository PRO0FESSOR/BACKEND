# operators 

# Arithmetic operators
a, b = 10, 5
print("Arithmetic Operators:")
print("Addition:", a + b)       # Addition
print("Subtraction:", a - b)    # Subtraction
print("Multiplication:", a * b) # Multiplication
print("Division:", a / b)       # Division
print("Floor Division:", a // b) # Floor Division
print("Modulus:", a % b)        # Modulus
print("Exponentiation:", a ** b) # Exponentiation

# Comparison operators
print("\nComparison Operators:")
print("Equal:", a == b)         # Equal to
print("Not Equal:", a != b)     # Not equal to
print("Greater than:", a > b)   # Greater than
print("Less than:", a < b)      # Less than
print("Greater or equal:", a >= b) # Greater than or equal to
print("Less or equal:", a <= b)    # Less than or equal to

# Logical operators
x, y = True, False
print("\nLogical Operators:")
print("AND:", x and y)          # AND
print("OR:", x or y)            # OR
print("NOT x:", not x)          # NOT

# Bitwise operators
print("\nBitwise Operators:")
print("AND:", a & b)            # Bitwise AND
print("OR:", a | b)            # Bitwise OR
print("XOR:", a ^ b)           # Bitwise XOR
print("Left Shift:", a << 1)   # Left shift
print("Right Shift:", a >> 1)  # Right shift

# Assignment operators
print("\nAssignment Operators:")
c = a
c += b   # c = c + b
print("Add and assign:", c)
c -= b   # c = c - b
print("Subtract and assign:", c)
c *= b   # c = c * b
print("Multiply and assign:", c)
c /= b   # c = c / b
print("Divide and assign:", c)

# Identity operators
print("\nIdentity Operators:")
print("a is b:", a is b)        # is
print("a is not b:", a is not b) # is not

# Membership operators
list1 = [1, 2, 3, 4, 5]
print("\nMembership Operators:")
print("3 in list1:", 3 in list1)     # in
print("6 not in list1:", 6 not in list1) # not in

